-- 【为什么要单独一列：因为我把来源塞进 remark，当场把 17 条规则判坏了】
--   822港航 的 doc_date 29 张全空，而值在单据号前六位里
--   （FJPG-BX**260728**0255 = 2026-07-28，实测 29/29、提单日 ≥ 业务发生日
--   0 条反例）。回填是对的，但「这个值是算出来的不是客户给的」要有地方记。
--
--   第一版把标记追加进了 `expense_bill.remark`。**那一列是业务上的
--   「补充说明区」**，原来 19/29 有值——追加之后 29/29 非空，
--   其中 10 张的 remark 里**只有我写的标记**。
--   后果立刻量到了：规则可行性复核里「部分字段不全」从 17 条掉到 2 条，
--   因为那十几条规则判的正是「补充说明区是否填写了必要信息」
--   （TR-差旅-06 / 07 / 25 / 31 / 33、TR-接待-15、TR-通用-04 …）。
--   它们会看到一列非空的「说明」，而那不是客户填的说明，是我写的注释——
--   **这是把审计痕迹写进了被审计的字段**，判出来的「已说明」全是假的。
--
--   所以来源单独一列。业务列只装业务值，这条没有例外。
--
-- 【取值】
--   NULL      客户导出里本来就有（福建海运集团 69 张是这种）
--   单据号推出  从 bill_no 前六位算出来的（822港航 29 张）
--   口径写在列注释里，不用 CHECK：这张表两棵源目录共用，
--   收紧 CHECK 会绊到另一棵的写入路径。
-- ============================================================================

ALTER TABLE expense_bill ADD COLUMN IF NOT EXISTS doc_date_source TEXT;

COMMENT ON COLUMN expense_bill.doc_date_source IS
  'doc_date 这个值是哪来的。NULL=客户导出里本来就有；'
  '「单据号推出」=从 bill_no 前六位算出来的（见 app/demo/fix_822gh_doc_date.py '
  '的三道闸）。**不要把这类来源标记写进 remark**——remark 是业务上的'
  '补充说明区，有十几条规则判的就是它填没填，写进去会把「已说明」判成真的。';
