-- ============================================================================
-- 0062 · trip_application.detail_read —— 「逐日表和签名日期这三块抽没抽过」
-- ----------------------------------------------------------------------------
-- 【编号】0061 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【为什么光有 extracted_from 不够】
--   extracted_from 回答的是「这一行**从哪来**」，不回答「**抽了哪些字段**」。
--   2026-11-01 读图批实测到的代价：那一轮 A01 的提示词只问了
--   出差起止日期和出差地点三个字段，逐日用餐/用车表没问、出差人签名日期
--   也没问；而 TR-通用-02 判的正好是这两样。规则看到空值，一律当成
--   「票面上没填」，**6 张单从 pending 变成命中，全是误报**。
--   当时的补丁是让规则认 extracted_from='审批单读图' 就 pending——
--   那是把「来源」当「覆盖面」用，**同一个来源的下一轮抽取覆盖面变了，
--   这个补丁就反过来变成漏判**（读到了也不判）。
--
-- 【这一列只回答一件事】
--   TRUE  = 逐日用餐表、逐日用车表、出差人签名日期这三块**已经抽过**。
--           抽过之后是空的，就是票面上真的空着，规则可以据此命中。
--   FALSE = **没抽过**。规则必须 pending，并在文案里写「没有读」。
--
--   存量回填的口径：
--     · '审批单文字层' 的 15 行 → TRUE。它们是从 PDF 文字层整表解析的，
--       逐日两张小表和签名日期本来就在解析范围内（90 行 trip_calendar
--       就是它们写的）。
--     · 其余（读图 8 行、OA 同步）→ 保持默认 FALSE，由装载程序自己改。
--   存量业务数据原则上不在迁移里改（同 0060/0061 文件头口径），
--   但这一行 UPDATE 是**结构性回填**：新列的语义对老行只有一个正确答案，
--   不回填的话 15 行已经判得好好的审批单会集体退回 pending。
--
-- 【为什么不是加第三个 extracted_from 取值】
--   来源和覆盖面是两个维度：同一个来源可以有好几轮覆盖面不同的抽取，
--   同一轮抽取也可能跨来源。塞进一列，下次加字段又要造一个新取值，
--   而且「按来源清掉这一批」会跟着错位——0061 刚为这件事付过一次代价。
-- ============================================================================

ALTER TABLE trip_application
    ADD COLUMN IF NOT EXISTS detail_read BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE trip_application SET detail_read = TRUE
 WHERE extracted_from = '审批单文字层' AND NOT detail_read;

COMMENT ON COLUMN trip_application.detail_read IS
  '逐日用餐表、逐日用车表、出差人签名日期这三块**抽没抽过**。'
  'TRUE 之后看到的空值才等于「票面上没填」，FALSE 时的空值只等于「没读」——'
  'TR-通用-02 靠它区分「命中」与「pending 并说明没读」。'
  '它和 extracted_from 是两个维度：那一列说来源，这一列说覆盖面。';
