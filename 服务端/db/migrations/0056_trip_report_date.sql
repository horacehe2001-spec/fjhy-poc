-- ============================================================================
-- 0056 · trip_application 加 report_date（填报日期），并订正 backfill_date 的口径
-- ----------------------------------------------------------------------------
-- 【编号】0055 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【订正一处口径错误：backfill_date 里装的不是回填日期】
--   出差审批单 PDF 上有两个不同的日期，业务含义完全不同：
--
--     填报日期   —— 填写人提交审批单的日期，**出差之前**
--     出差人签名 —— 出差回来之后，出差人自己签字确认的日期，**出差之后**
--
--   实测 FJPG-BX2607240109：
--     填报日期 2026-07-20 11:04:15，出差 07-22~07-23，
--     出差人签名「阚绮棠 2026-07-24」。
--   两个日期差 4 天、分列表头与表尾，是两件事。
--
--   而 trip_application.backfill_date 这一列的名字就是「回填日期」，
--   装的却是**填报日期**。写入那一处（load_822gh_attachments.parse_trip）
--   把表头的 `hdr["填报日期"]` 填进了 backfill_date。
--
--   这不是无害的命名偏差：人工驳回意见里有两条判的就是这件事——
--     「出差审批未体现出差人回填情况（签字及日期）」FJPG-BX2603270004
--     「补充审批单下面回填日期」                    FJPG-BX2606101698
--   拿填报日期去判「有没有回填」，**15 份全部有值，一条都判不出来**，
--   而且看上去是「全部通过」。这是「闸在跑但判的是错的字段」那一类，
--   比闸没跑更难发现。
--
--   所以：backfill_date 的口径订正为**出差人签名日期**，
--   填报日期挪到新列 report_date，两个日期都留着，不丢数据。
--
-- 【为什么是加列而不是改写】
--   填报日期本身有用（TR-接待-01「审批应早于接待发生」那一类要用它），
--   直接把 backfill_date 的内容覆盖掉就把它弄丢了。
--
-- 【这张表两棵源目录共用】
--   福建海运集团（fjhy）那边 trip_application 是演示合成的，
--   backfill_date 存量 15 行全属 822gh。新列可空，不动存量。
-- ============================================================================

ALTER TABLE trip_application ADD COLUMN IF NOT EXISTS report_date DATE;

COMMENT ON COLUMN trip_application.report_date IS
  '填报日期：填写人提交出差审批单的日期，在出差之前。'
  '出差审批单 PDF 表头那一格。**不要和 backfill_date 混**。';

COMMENT ON COLUMN trip_application.backfill_date IS
  '出差人回填签名的日期：出差结束后出差人本人签字确认的日期，在出差之后。'
  '出差审批单 PDF 表尾「出差人签名 <姓名> <日期>」那一格。'
  '为空 = 审批单没有体现出差人回填情况（人工驳回过两次）。'
  '**0056 之前这一列错装了填报日期**，判「有没有回填」时 15 份全有值、'
  '一条都判不出来，所以订正。填报日期现在在 report_date。';
