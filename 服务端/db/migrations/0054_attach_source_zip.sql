-- ============================================================================
-- 0054 · attachment.source_kind 增加「zip附件包」
-- ----------------------------------------------------------------------------
-- 【编号】0053 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【为什么要加一个取值】
--   现有三个取值的语义是明确的：
--       xlsx内嵌   附件是嵌在报账单 xlsx 导出里的（福建海运集团那 273 个）
--       演示合成   为演示造出来的
--       上传       用户从制度文件库那条上传路径传进来的
--   822港航 的 570 个附件哪个都不是：客户交付的是**三个嵌套 zip**
--   （外层一个包、里面一张单一个包，内层才是 PDF/JPG）。
--
--   硬塞成「上传」的后果不是存不进去，是**以后查不清来源**：
--   「上传」在这套系统里指的是文件库那条有审计留痕的上传链路，
--   而这批文件根本没走那条链路，没有 doc_lib_upload 记录可查。
--   同一个取值两种来源，就是这个项目里刚踩过两次的那个坑
--   （payee_account 一边是银行卡号一边是账户名；
--     rule.feasibility 一边是客户评估一边是 POC 结论）。
--
-- 【放宽 CHECK 是加法，不会打破存量】
--   现有 273 行全是前三个取值，新增一个允许值不影响任何一行。
--   **这张表是两棵源目录共用的**（同一个库），所以这里只放宽、不收紧、
--   不改列类型——收紧会让另一棵树已经写进去的数据变成非法。
-- ============================================================================

ALTER TABLE attachment DROP CONSTRAINT IF EXISTS ck_att_source_kind;
ALTER TABLE attachment ADD CONSTRAINT ck_att_source_kind
    CHECK (source_kind = ANY (ARRAY['xlsx内嵌'::text, '演示合成'::text,
                                    '上传'::text, 'zip附件包'::text]));

COMMENT ON COLUMN attachment.source_kind IS
  '附件是怎么进来的。xlsx内嵌=嵌在报账单导出里；演示合成=为演示造的；'
  '上传=走文件库上传链路（有 doc_lib_upload 留痕）；'
  'zip附件包=客户交付的嵌套 zip（外层一个包、一张单一个内层包），'
  '**没有上传留痕，来源靠 source_ref 记内层包名**。';
