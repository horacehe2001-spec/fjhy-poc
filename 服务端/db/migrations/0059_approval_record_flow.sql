-- 0059 · approval_record.flow（这条审批记录属于哪条流程）
-- ----------------------------------------------------------------------------
-- 【编号】0058 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【为什么要加：我把两条流程的流水混进了同一张表，流程图当场显示错数】
--   2026-11-01 从业务接待审批单 PDF 解出 8 条流转记录写进 approval_record
--   （节点名：发起节点 / 部门负责人 / 分管领导 / 主管领导）。
--   而 approval_record 原本装的是**报账流程**的审批记录
--   （福建海运集团 388 条：AI审核 / 共享审核 / 总经理 / 撤回 / 流程结束…）。
--
--   两条流程都有「分管领导」这个角色名。onto_process.build() 算「实测次数」
--   是按**节点名**匹配本体节点的，于是 822港航 的报账流程图上
--   P05 分管领导 显示 `measured = 2`——**而这 29 张报账单一次都没被
--   分管领导审过**，那 2 次是业务接待审批单的审批。
--
--   这不是显示问题：流程本体页上的「实测次数」是用来核对「本体画的流程
--   和真实走的流程差多少」的，混了别条流程的记录，这个核对整段不可信。
--   和 0044 那次的教训是同一类（跨实例混数），只是这次跨的是**流程**
--   而不是实例——**实例、版本、流程是三个维度，每一句都要带齐**。
--
-- 【取值】
--   NULL      报账流程（存量 388 条全是这种，不回填，保持原样）
--   业务接待审批 业务接待审批单 PDF 上的流转记录
--   口径写在列注释里，不加 CHECK：这张表两棵源目录共用，
--   收紧 CHECK 会绊到另一棵的写入路径。
--
-- 【为什么不是把节点名加前缀】
--   另一条路是把 EN16 的取值写成「接待审批·分管领导」这种带前缀的名字，
--   那样匹配不上 P05，问题也没了。但那是**把流程信息塞进名字里**：
--   节点名就是节点名，它属于哪条流程是另一个维度。
--   塞进名字之后，「所有流程里的分管领导节点」就查不出来了。
-- ============================================================================

ALTER TABLE approval_record ADD COLUMN IF NOT EXISTS flow TEXT;

COMMENT ON COLUMN approval_record.flow IS
  '这条审批记录属于哪条流程。NULL=报账流程（流程本体画的那条）；'
  '「业务接待审批」=业务接待审批单上的流转记录，**那是另一条 OA 流程**。'
  '算流程本体的「实测次数」时必须按这一列过滤——两条流程都有'
  '「分管领导」这种角色名，不过滤会把接待审批的次数计到报账流程节点上。';
