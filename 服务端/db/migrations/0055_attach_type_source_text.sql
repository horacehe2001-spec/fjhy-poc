-- ============================================================================
-- 0055 · attachment.type_source 增加「文字层解析」
-- ----------------------------------------------------------------------------
-- 【编号】0054 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【为什么要加一个取值】
--   现有三个取值记的是「这个附件的类型是怎么定下来的」：
--       读图判定   多模态模型读图判的（真出网、真计费）
--       人工指定   人点的
--       演示合成   生成器造的，类型是造的时候就知道的
--   822港航 的 147 个附件里有 72 个的类型是**第四种来路**：
--   PDF 有文字层，已经被确定性解析过了——
--     53 个文件名是「发票附件-<发票号>.pdf」，而那个发票号已经解析进
--       invoice 表，票面类型（数电普票/专票/铁路电子客票）和项目明细
--       （*住宿服务*、*生产生活服务*代订机票）都在库里
--     19 个文件名是「港航本部出差审批流程*.pdf」「出差申请单*.pdf」，
--       其中 15 个已经解析进 trip_application
--   这些的类型是**算出来的，不是读图判的，也不是人点的**。
--
--   硬塞成「读图判定」的后果：事后问「哪些附件的类型是模型判的、
--   该不该复核」，答案就全错了——而这条链路的全部价值就在于
--   「模型判的结论要能被挑出来复核」（见 attachment_classify 的三条纪律）。
--   硬塞成「人工指定」更坏：没有人看过它们。
--
--   顺带省掉 72 次读图调用。**但省钱不是加这个值的理由**，
--   理由是来源要记对；省下的调用是结果。
--
-- 【放宽 CHECK 是加法，不会打破存量】
--   现有行全是前三个取值。这张表两棵源目录共用，所以只放宽不收紧。
-- ============================================================================

ALTER TABLE attachment DROP CONSTRAINT IF EXISTS ck_att_type_source;
ALTER TABLE attachment ADD CONSTRAINT ck_att_type_source
    CHECK (type_source IS NULL OR type_source = ANY (
        ARRAY['读图判定'::text, '人工指定'::text, '演示合成'::text,
              '文字层解析'::text]));

COMMENT ON COLUMN attachment.type_source IS
  '附件类型是怎么定下来的。读图判定=多模态模型读图（结论要能被挑出来复核）；'
  '人工指定=人点的；演示合成=生成器造的；'
  '文字层解析=PDF 有文字层，由已解析的发票号/文件名确定性算出来的，'
  '**既不是模型判的也不是人点的**。';
