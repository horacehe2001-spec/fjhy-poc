-- ============================================================================
-- 0061 · trip_application.extracted_from 放开第三种来源「审批单文字层」
-- ----------------------------------------------------------------------------
-- 【编号】0060 之后接着走。0040–0052 属另一棵源目录（见 0053 文件头）。
--
-- 【这一列原来只有两种取值，而实际上有三条链路】
--   0038 建这一列时只认两种：
--       NULL + synced_from_oa=TRUE  → OA 系统同步
--       '审批单读图'                 → attachment_extract 读图抽取
--   CHECK 约束 ck_ta_extracted_from 把取值钉死在这两种上。
--
--   2026-11-01 实测出第三条链路：**PDF 文字层直接解析**。
--   822港航 的 15 份出差审批单是带文字层的 PDF，
--   app/demo/load_822gh_attachments.py 零模型调用就把表头字段和
--   逐日用餐/用车解出来了（90 行 trip_calendar）。
--   它没有第三个取值可选，于是写了 '审批单读图'——**那是个说谎的值**，
--   这 15 行一次模型调用都没花过。
--
-- 【后果不是「不好看」，是会删错数据】
--   同一天，读图批给同一张表写了 7 条真·读图的行
--   （attachment_extract_fields._apply，app_no 形如 ATT-<附件号>）。
--   两批撞在同一个取值上之后：
--     · 「按来源清掉读图那一批再重放」会连带删掉那 15 行，
--       以及 CASCADE 挂在它们下面的 **90 行逐日记录**
--     · 对外报「读图读出了多少份审批单」会报成 22，实际是 7
--   第一条在 app/demo/read_822gh_vision_batch.py 的重放闸上当场拦住了
--   （那道闸数了一下逐日行数，发现不是 0 就中止），没有真删。
--
-- 【改法：放开取值，不是去掉约束】
--   约束本身是对的——它防的是「来源这一列被写成随便什么字符串」。
--   要做的是把第三种真实来源加进允许集合，并在注释里写清三者的区别。
--   存量数据不在这里改：迁移改表结构，业务数据由装载程序自己重写
--   （同 0060 文件头的口径）。
-- ============================================================================

ALTER TABLE trip_application DROP CONSTRAINT IF EXISTS ck_ta_extracted_from;

ALTER TABLE trip_application ADD CONSTRAINT ck_ta_extracted_from
    CHECK (extracted_from IS NULL
           OR extracted_from IN ('审批单读图', '审批单文字层'));

COMMENT ON COLUMN trip_application.extracted_from IS
  '这一行的出差审批单是怎么进来的，三选一：'
  'NULL 且 synced_from_oa=TRUE → OA 系统同步（唯一的真实集成链路）；'
  '「审批单读图」→ attachment_extract 把审批单**图片**发给多模态模型读出来的'
  '（计费，app_no 形如 ATT-<附件号>）；'
  '「审批单文字层」→ 从带文字层的审批单 PDF 直接解析，**零模型调用**。'
  '三者可信度不同，而且「按来源清掉某一批」要靠它——'
  '两批共用一个取值会删错数据（2026-11-01 差点删掉 90 行逐日记录）。';
